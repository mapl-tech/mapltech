// node scripts/vsl-poster.mjs
//
// Writes src/components/bio/_poster.scss: the bio page video's poster as a
// 960px AVIF (about 7 KB), inlined in the stylesheet the page already loads.
// On phones the poster then paints with the page itself instead of waiting
// for its own request, which is what made it the slow part of the first
// screen (Lighthouse's phone LCP). Run it again whenever the poster changes
// (public/images/VSL/mapl-tech-vsl-v1-poster.jpg, the video's first frame).
import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

const SOURCE = 'public/images/VSL/mapl-tech-vsl-v1-poster.jpg';
const OUT = 'src/components/bio/_poster.scss';

const avif = await sharp(SOURCE).resize(960).avif({ quality: 40, effort: 9 }).toBuffer();
writeFileSync(
  OUT,
  `// Generated by scripts/vsl-poster.mjs from ${SOURCE} (960px AVIF, ${avif.length} bytes). Do not edit.\n` +
    `$avif: 'data:image/avif;base64,${avif.toString('base64')}';\n`,
);
console.log(`${OUT}: ${avif.length} bytes of AVIF`);
